<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Collection;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\Eloquent\SoftDeletes;

/**
 * Represents a message associated with a support ticket.
 *
 * Messages can form parent-child relationships, allowing users and support
 * agents to reply to specific messages within the same ticket.
 *
 * @property int $id
 * @property int $ticket_id
 * @property int $user_id
 * @property int|null $parent_id
 * @property string $message
 * @property string $type
 * @property bool $is_internal
 * @property bool $is_edited
 * @property \Illuminate\Support\Carbon|null $edited_at
 * @property array<int, mixed>|null $attachments
 * @property int $version
 * @property \Illuminate\Support\Carbon|null $created_at
 * @property \Illuminate\Support\Carbon|null $updated_at
 * @property \Illuminate\Support\Carbon|null $deleted_at
 *
 * @property-read TicketModel $ticket
 * @property-read User $user
 * @property-read TicketMessageModel|null $parentMessage
 * @property-read Collection<int, TicketMessageModel> $replies
 * @property-read Collection<int, TicketAttachmentModel> $messageAttachments
 */
class TicketMessageModel extends Model
{
    use HasFactory;
    use SoftDeletes;

    /**
     * The table associated with the model.
     *
     * @var string
     */
    protected $table = 'ticket_messages';

    /**
     * The Snowflake ID is generated by the application.
     *
     * @var bool
     */
    public $incrementing = false;

    /**
     * The primary key type.
     *
     * @var string
     */
    protected $keyType = 'int';

    /**
     * Attributes that can be mass assigned.
     *
     * @var array<int, string>
     */
    protected $fillable = [
        'id',
        'ticket_id',
        'user_id',
        'parent_id',
        'message',
        'type',
        'is_internal',
        'is_edited',
        'edited_at',
        'attachments',
        'version',
    ];

    /**
     * Attribute casting definitions.
     *
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'id' => 'integer',
            'ticket_id' => 'integer',
            'user_id' => 'integer',
            'parent_id' => 'integer',
            'is_internal' => 'boolean',
            'is_edited' => 'boolean',
            'edited_at' => 'datetime',
            'attachments' => 'array',
            'is_edited' => 'boolean',
            'version' => 'integer',
        ];
    }

    /**
     * Get the ticket to which this message belongs.
     *
     * @return BelongsTo<TicketModel, $this>
     */
    public function ticket(): BelongsTo
    {
        return $this->belongsTo(TicketModel::class, 'ticket_id');
    }

    /**
     * Get the author of this message.
     *
     * @return BelongsTo<User, $this>
     */
    public function user(): BelongsTo
    {
        return $this->belongsTo(User::class, 'user_id');
    }

    /**
     * Get the message this message replies to.
     *
     * A null parent_id indicates a top-level message.
     *
     * @return BelongsTo<TicketMessageModel, $this>
     */
    public function parentMessage(): BelongsTo
    {
        return $this->belongsTo(
            TicketMessageModel::class,
            'parent_id'
        );
    }

    /**
     * Get the direct replies to this message.
     *
     * @return HasMany<TicketMessageModel, $this>
     */
    public function replies(): HasMany
    {
        return $this->hasMany(
            TicketMessageModel::class,
            'parent_id'
        )->orderBy('created_at');
    }

    /**
     * Get attachments associated directly with this message.
     *
     * @return HasMany<TicketAttachmentModel, $this>
     */
    public function messageAttachments(): HasMany
    {
        return $this->hasMany(
            TicketAttachmentModel::class,
            'message_id'
        );
    }
}